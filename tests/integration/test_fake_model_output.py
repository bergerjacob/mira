"""
Integration tests simulating "LLM generated block list → build → verify" pipeline.

Each test loads a circuit fixture (as if it were generated by an LLM),
builds it in Minecraft, and verifies the circuit behaves correctly.
All tests require a running Minecraft server (RCON on localhost:25575).
"""
import pytest


# ---------------------------------------------------------------------------
# Individual circuit tests — one per fixture
# ---------------------------------------------------------------------------

@pytest.mark.server
def test_direct_power_lamp(load_circuit, build_and_verify, test_region):
    """Redstone block directly powers a lamp → lamp should be lit."""
    fixture = load_circuit("direct_power_lamp")
    ctx = build_and_verify(fixture, test_region)
    ctx.assert_block([1, 0, 0], "minecraft:redstone_lamp[lit=true]")


@pytest.mark.server
def test_lever_lamp(load_circuit, build_and_verify, test_region):
    """Lever → dust → lamp: flip lever ON, verify lamp lights."""
    fixture = load_circuit("lever_lamp")
    ctx = build_and_verify(fixture, test_region)
    # Initial: lamp off
    ctx.assert_block([2, 0, 0], "minecraft:redstone_lamp[lit=false]")
    # Flip lever
    ctx.set_block([0, 0, 0], "minecraft:lever[facing=east,powered=true]")
    ctx.tick(20)
    # Final: lamp on
    ctx.assert_block([2, 0, 0], "minecraft:redstone_lamp[lit=true]")


