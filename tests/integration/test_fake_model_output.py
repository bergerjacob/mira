# ---------------------------------------------------------------------------
# Fixture-driven generic test — runs verification spec from every fixture
# ---------------------------------------------------------------------------

FIXTURE_NAMES = [
    "direct_power_lamp",
    "lever_lamp",
    "lever_lamp_direct",
    "fan_out_lamp",
    "wire_propagation",
    "piston_extend",
    "broken_lamp",
    "broken_wire",
]


@pytest.mark.server
@pytest.mark.parametrize("fixture_name", FIXTURE_NAMES)
def test_fixture_verification(fixture_name, load_circuit, build_circuit, ctx, test_region):
    """
    Generic fixture-driven test: load a circuit, build it, then execute the
    verification spec embedded in the fixture JSON (initial_checks, actions,
    tick_steps, final_checks). This validates the verification execution engine.
    """
    fixture = load_circuit(fixture_name)
    build_circuit(fixture, test_region)

    verification = fixture.get("verification", {})
    initial_checks = verification.get("initial_checks", [])
    actions = verification.get("actions", [])
    tick_steps = verification.get("tick_steps", 0)
    final_checks = verification.get("final_checks", [])

    # Run initial checks
    for check in initial_checks:
        ctx.assert_block(check["pos"], check["expected"])

    # Perform actions
    for action in actions:
        if action["type"] == "set_block":
            ctx.set_block(action["pos"], action["state"])
        else:
            raise ValueError(f"Unknown action type: {action['type']}")

    # Tick
    if tick_steps:
        ctx.tick(tick_steps)

    # Run final checks
    for check in final_checks:
        ctx.assert_block(check["pos"], check["expected"])
